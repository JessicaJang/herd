#!/usr/bin/env bash
# gen-agents.sh: make the OpenCode subagent files for eye from herd.yaml.
# herd.yaml stays the only config file. Run this after you change `models`.
set -euo pipefail

HERD="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$HERD/.opencode/agents"
mkdir -p "$OUT"

python3 - "$HERD/herd.yaml" "$OUT" <<'PY'
import sys, pathlib
try:
    import yaml
except ImportError:
    sys.exit("PyYAML is missing. Run: sudo apt install python3-yaml")

cfg = yaml.safe_load(open(sys.argv[1]))
out = pathlib.Path(sys.argv[2])
models = cfg["models"]

# name -> (model, role file in skills/eye/references, description)
agents = {
    "eye-triage":   (models["triage"],   "triage.md",   "eye layer 2: summarise a diff, label risk, pick the review tier"),
    "eye-reviewer": (models["reviewer"], "reviewer.md", "eye layer 3: single reviewer for the quick tier"),
    "eye-lead":     (models["judgment"], "lead.md",     "eye layers 4-5: teaching and the final ranked report"),
}
for i, m in enumerate(models.get("panel", [])):
    agents[f"eye-panel-{i}"] = (m, "reviewer.md", f"eye layer 3: panel reviewer {i} (standard and deep tiers)")

# Remove old generated files, so that a smaller panel leaves no stale agents.
for pattern in ("eye-*.md", "herd-*.md"):
    for old in out.glob(pattern):
        old.unlink()

PERMS = """permission:
  edit: deny
  webfetch: deny
  bash:
    "*": deny
    "git diff*": allow
    "git log*": allow
    "git show*": allow
    "git blame*": allow
    "git -C * diff*": allow
    "git -C * show*": allow
    "git -C * log*": allow
    "gh pr diff*": allow
    "gh pr view*": allow
    "gh stack view*": allow
    "rg *": allow
    "grep *": allow"""

for name, (model, ref, desc) in agents.items():
    (out / f"{name}.md").write_text(f"""---
description: "{desc}"
mode: subagent
model: "{model}"
{PERMS}
---
<!-- Generated by scripts/gen-agents.sh from herd.yaml. Do not edit by hand. -->
Read ~/herd/skills/eye/references/{ref} and follow it exactly.
You are read-only. Do not edit files. Do not post anything.
""")
    print(f"  ok    .opencode/agents/{name}.md  ({model})")

# herd agents for the pstack-derived skills (see skills/_shared/subagents.md).
READONLY = """permission:
  edit: deny
  webfetch: deny"""
RUNNER = """permission:
  edit:
    "*": deny
    "~/branches/.herd/arena/**": allow
    "/home/jess/branches/.herd/arena/**": allow
  webfetch: deny"""
herd = {
    "herd-explainer": (models["judgment"], READONLY, "Read-only explorer and explainer for how, why and teach"),
    "herd-judge":     (models.get("judge", models["judgment"]), READONLY, "Read-only cross-judge for arena and trail review for show-me-your-work"),
}
for i, m in enumerate(models.get("panel", [])):
    herd[f"herd-runner-{i}"] = (m, RUNNER, f"Runner {i} for arena, interrogate and blast-radius. Edits only in its own worktree")
for name, (model, perms, desc) in herd.items():
    (out / f"{name}.md").write_text(f"""---
description: "{desc}"
mode: subagent
model: "{model}"
{perms}
---
<!-- Generated by scripts/gen-agents.sh from herd.yaml. Do not edit by hand. -->
Follow ~/herd/skills/_shared/subagents.md and the brief that you are given.
Never post, push, or change a cloud resource.
""")
    print(f"  ok    .opencode/agents/{name}.md  ({model})")
PY
